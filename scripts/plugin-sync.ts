/**
 * Writes the parts of `plugin/` that are derived from the code, so the plugin
 * cannot say something the server does not.
 *
 * Three things: the hook bundle (below), the skill, which is `skillDocument()` verbatim -- the same text
 * `pnpm install:mcp --write-skill` writes and the server sends at initialize
 * -- and the manifests' version (Claude Code's, Codex's, Cursor's and Cursor's
 * marketplace entry), which follows `package.json` the way
 * `server.json` and `SERVER_INFO` do. `scripts/plugin.test.ts` reads both back
 * and fails when either has drifted, which is what makes running this on a
 * change to `BASE` a build step rather than a habit.
 *
 * The hook bundle is `mcp/hook/index.ts` and everything it imports, folded into
 * one ES module that needs nothing but node's built-ins: a plugin is copied
 * into a cache directory with no `node_modules` beside it, so a hook that
 * imported a package would fail on every machine but this one.
 *
 * Nothing else in `plugin/` is generated: the MCP entries, the hooks files,
 * `hooks/run.sh` and the README are written by hand and read by a person.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { skillDocument } from "../mcp/tools";
import { bundleNodeScript } from "./bundle-node";

export const PLUGIN_ROOT = join(__dirname, "..", "plugin");
export const SKILL_PATH = join(PLUGIN_ROOT, "skills", "todox", "SKILL.md");
export const MANIFEST_PATH = join(PLUGIN_ROOT, ".claude-plugin", "plugin.json");
/**
 * The same plugin directory, described to Codex and to Cursor: their
 * manifests point at the shared skill and hook bundle and differ only in the
 * hooks file and MCP entry each agent reads (docs/competitors/mem0.md).
 */
export const OTHER_MANIFEST_PATHS = [
  join(PLUGIN_ROOT, ".codex-plugin", "plugin.json"),
  join(PLUGIN_ROOT, ".cursor-plugin", "plugin.json"),
];
/** Cursor's marketplace entry repeats the version; Codex's does not carry one. */
export const CURSOR_MARKETPLACE_PATH = join(__dirname, "..", ".cursor-plugin", "marketplace.json");
export const HOOK_BUNDLE_PATH = join(PLUGIN_ROOT, "hooks", "todox-hook.mjs");
const HOOK_BANNER =
  "// Generated by `pnpm plugin:sync` from mcp/hook/. Do not edit: edit the source and re-run it.";

/** What the checked-in hook bundle must equal. */
export const expectedHookBundle = (): string => bundleNodeScript("mcp/hook/index.ts", HOOK_BANNER);

/** What the checked-in skill must equal. */
export const expectedSkill = (): string => skillDocument();

/** What the checked-in manifest's `version` must equal. */
export const expectedVersion = (): string =>
  (JSON.parse(readFileSync(join(__dirname, "..", "package.json"), "utf8")) as { version: string })
    .version;

/** The manifest with its version set, formatted the way it is checked in. */
export function manifestWithVersion(raw: string, version: string): string {
  const manifest = JSON.parse(raw) as Record<string, unknown>;
  return `${JSON.stringify({ ...manifest, version }, null, 2)}\n`;
}

/** The Cursor marketplace with every entry's version set. */
export function marketplaceWithVersion(raw: string, version: string): string {
  const marketplace = JSON.parse(raw) as { plugins: Record<string, unknown>[] };
  const plugins = marketplace.plugins.map((p) => ({ ...p, version }));
  return `${JSON.stringify({ ...marketplace, plugins }, null, 2)}\n`;
}

if (require.main === module) {
  writeFileSync(HOOK_BUNDLE_PATH, expectedHookBundle());
  console.log(`wrote ${HOOK_BUNDLE_PATH}`);
  writeFileSync(SKILL_PATH, expectedSkill());
  for (const path of [MANIFEST_PATH, ...OTHER_MANIFEST_PATHS])
    writeFileSync(path, manifestWithVersion(readFileSync(path, "utf8"), expectedVersion()));
  writeFileSync(
    CURSOR_MARKETPLACE_PATH,
    marketplaceWithVersion(readFileSync(CURSOR_MARKETPLACE_PATH, "utf8"), expectedVersion()),
  );
  console.log(`wrote ${SKILL_PATH}`);
  console.log(`wrote ${MANIFEST_PATH} (version ${expectedVersion()})`);
}
